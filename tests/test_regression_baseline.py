METRIC_KEYS = [
    ("entropy_a", lambda a, b: m.shannon_entropy(a)),
    ("entropy_b", lambda a, b: m.shannon_entropy(b)),
    ("npcr", lambda a, b: m.npcr(a, b)),
    ("uaci", lambda a, b: m.uaci(a, b)),
    ("bit_difference", lambda a, b: m.bit_difference_ratio(a, b)),
    ("chi_square", lambda a, b: m.chi_square_uniformity(b)[0]),
    ("chi_square_p", lambda a, b: m.chi_square_uniformity(b)[1]),
]


@pytest.mark.parametrize("metric_key,fn", METRIC_KEYS)
@pytest.mark.parametrize("case", ["mixed", "shift_only"])
def test_metrics_match_notebook(vectors, metric_key, fn, case):
    vector = vectors["metric_vectors"][case]
    a = np.frombuffer(bytes.fromhex(vector["a_hex"]), dtype=np.uint8)
    b = np.frombuffer(bytes.fromhex(vector["b_hex"]), dtype=np.uint8)
    expected = vector[metric_key]
    actual = fn(a, b)
    if isinstance(expected, float) and math.isnan(expected):
        assert math.isnan(float(actual))
    else:
        assert actual == pytest.approx(expected, rel=1e-12, abs=1e-12), (
            f"{case}/{metric_key}: library={actual} notebook={expected}"
        )


def test_correlation_matches_notebook(vectors):
    for case in ("mixed", "shift_only"):
        vector = vectors["metric_vectors"][case]
        a = np.frombuffer(bytes.fromhex(vector["a_hex"]), dtype=np.uint8)
        b = np.frombuffer(bytes.fromhex(vector["b_hex"]), dtype=np.uint8)
        assert m.adjacent_byte_correlation(a) == pytest.approx(
            vector["correlation_a"], rel=1e-12
        )
        assert m.adjacent_byte_correlation(b) == pytest.approx(
            vector["correlation_b"], rel=1e-12
        )


def test_monobit_matches_notebook_except_documented_underflow(vectors):
    """Monobit agrees with the notebook unless the notebook's unsigned
    subtraction underflowed (zeros > ones) — a documented baseline defect
    (docs/KNOWN_ISSUES.md).  Where it underflowed, the library must instead
    return the mathematically exact value of the same formula."""
    from scipy.stats import norm

    for case in ("mixed", "shift_only"):
        vector = vectors["metric_vectors"][case]
        b = np.frombuffer(bytes.fromhex(vector["b_hex"]), dtype=np.uint8)
        assert m.monobit_frequency_test(b) == pytest.approx(
            vector["monobit_b"], rel=1e-12
        )

    underflow = vectors["metric_vectors"]["low_entropy"]
    b = np.frombuffer(bytes.fromhex(underflow["b_hex"]), dtype=np.uint8)
    bits = np.unpackbits(b)
    ones, zeros = int(bits.sum()), bits.size - int(bits.sum())
    exact = 2 * (1 - norm.cdf(abs(ones - zeros) / np.sqrt(bits.size)))
    assert zeros > ones  # precondition for the notebook's underflow
    assert underflow["monobit_b"] == 0.0  # notebook's wrapped-around result
    assert m.monobit_frequency_test(b) == pytest.approx(float(exact))
    assert m.monobit_frequency_test(b) != pytest.approx(underflow["monobit_b"])


def test_truncated_notebook_behavior_reproducible(vectors):
    """allow_truncate=True reproduces the notebook's min-length numbers."""
    vector = vectors["metric_vectors"]["truncation_case"]
    a = np.frombuffer(bytes.fromhex(vector["a_hex"]), dtype=np.uint8)
    b = np.frombuffer(bytes.fromhex(vector["b_hex"]), dtype=np.uint8)
    assert a.size != b.size  # precondition: mismatched inputs
    assert m.npcr(a, b, allow_truncate=True) == pytest.approx(vector["npcr_truncated"])
    assert m.uaci(a, b, allow_truncate=True) == pytest.approx(vector["uaci_truncated"])
    assert m.bit_difference_ratio(a, b, allow_truncate=True) == pytest.approx(
        vector["bit_difference_truncated"]
    )
    with pytest.raises(ValueError):
        m.npcr(a, b)


