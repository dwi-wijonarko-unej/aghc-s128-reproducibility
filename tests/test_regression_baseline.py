@pytest.mark.parametrize("index", range(13), ids=lambda i: f"vec{i}")
def test_ciphertext_matches_baseline(vectors, index):
    vector = vectors["cipher_vectors"][index]
    plaintext = np.frombuffer(bytes.fromhex(vector["plaintext_hex"]), dtype=np.uint8)
    result = encrypt_bytes(plaintext, vector["n_input"], vector["password"])
    assert result.ciphertext_sha3_256 == vector["ciphertext_sha3_256"], (
        f"ciphertext diverged for {vector['password']} n={vector['n_input']} "
        f"size={vector['plaintext_size']}"
    )


@pytest.mark.parametrize("index", range(13), ids=lambda i: f"vec{i}")
def test_key_matrix_matches_baseline(vectors, index):
    vector = vectors["cipher_vectors"][index]
    material = generate_valid_key(vector["n_input"], vector["password"])
    import hashlib

    key_digest = hashlib.sha3_256(
        material.matrix.astype(np.uint8).tobytes()
    ).hexdigest()
    inverse_digest = hashlib.sha3_256(
        material.inverse.astype(np.uint8).tobytes()
    ).hexdigest()
    assert key_digest == vector["key_matrix_sha3_256"]
    assert inverse_digest == vector["key_inverse_sha3_256"]
    assert material.trial_index == vector["trial_index"]


@pytest.mark.parametrize("index", range(13), ids=lambda i: f"vec{i}")
def test_round_trip_matches_baseline(vectors, index):
    vector = vectors["cipher_vectors"][index]
    plaintext = np.frombuffer(bytes.fromhex(vector["plaintext_hex"]), dtype=np.uint8)
    encrypted = encrypt_bytes(plaintext, vector["n_input"], vector["password"])
    decrypted = decrypt_bytes(
        encrypted.ciphertext, vector["n_input"], vector["password"],
        trial_index=vector["trial_index"],
    )
    assert decrypted.plaintext_sha3_256 == vector["plaintext_sha3_256"]
    np.testing.assert_array_equal(decrypted.plaintext, plaintext)


def test_nonzero_trial_vector_present(vectors):
    """At least one vector must exercise trial_index > 0 (retry path)."""
    nonzero = [v for v in vectors["cipher_vectors"] if v["trial_index"] > 0]
    assert nonzero, "expected at least one vector with trial_index > 0"
    assert any(v["trial_index"] == 5 for v in nonzero)


def test_ciphertext_hex_matches_baseline(vectors):
    for vector in vectors["cipher_vectors"]:
        if vector.get("ciphertext_hex"):
            plaintext = np.frombuffer(
                bytes.fromhex(vector["plaintext_hex"]), dtype=np.uint8
            )
            result = encrypt_bytes(plaintext, vector["n_input"], vector["password"])
            assert result.ciphertext.tobytes().hex() == vector["ciphertext_hex"]


